"""The controlled vocabulary the eval set is drawn from.

The quality standard is blunt about where task names may come from: *"Task names
must come from the robotics downstream task map; inventing them is not allowed."*
That map is a spreadsheet of 1,965 canonical tasks, each with a stable
`RDT-#####` id, an instruction template, a domain, a task family and a
granularity. `eval/task_map.csv` is the slice of it this repository needs — see
`eval/README.md` for the source, the owner and the retrieval date.

Three things have to happen before those rows can be used as eval queries, and
each is a judgement worth stating out loud rather than burying in a
comprehension:

1. **Not every canonical task is footage a person can be filmed doing.** The map
   covers robot benchmarks as well as human activity: quadruped parkour, a
   simulated humanoid sitting on a chair, "move banana to the sum of two plus
   one". Those are real entries in the vocabulary and useless as a search query,
   so they are excluded by rule — by domain, by family, and by wording — and the
   count dropped by each rule is reported rather than silently applied.

2. **The family column is not yet internally consistent.** `Cleaning`,
   `Cleaning & Hygiene` and `Cleaning & Surface Treatment` are three spellings
   of one family; `Pick and place` and `Pick–Place & Transport` are two more.
   Stratifying on the raw column would put four samples in what is really one
   bucket, so the aliases below collapse onto a canonical name. The sheet is not
   edited — the normalisation is frozen here, in the consumer, where it can be
   tested.

3. **An instruction is not a query.** `Assemble the cabinet.` sent to a video
   platform is an instruction to a robot; what a person searching for footage
   types is *someone assembling the cabinet*. The conversion is mechanical and
   is kept mechanical, because a model rewriting 200 queries would make the set
   unreproducible.

Sampling is deterministic. The eval set is frozen (`eval/queries.json`) and a
frozen set that cannot be regenerated byte-for-byte is not frozen, so nothing
here touches `random` without a seed and nothing depends on dict ordering that
is not already insertion ordered.
"""

