# --- the difficulty axis -------------------------------------------------------
#
# The eval spec stratifies on Easy / Medium / Hard and will not accept a batch
# that is green on easy and red on hard. The task map does not carry difficulty,
# but it carries granularity, and granularity is the closest honest proxy: a
# primitive skill is a few seconds of one motion, a long-horizon activity is a
# sequence somebody has to hold together. Stated as a mapping so it can be
# argued with.
DIFFICULTY_BY_GRANULARITY: dict[str, str] = {
    "primitive skill": "easy",
    "atomic task": "easy",
    "composite task": "medium",
    "benchmark task": "medium",
    "long-horizon activity": "hard",
    "long-horizon task": "hard",
}

# The target mix, from the eval spec's difficulty axis (20 / 50 / 30).
DIFFICULTY_MIX: dict[str, float] = {"easy": 0.20, "medium": 0.50, "hard": 0.30}

# --- instruction to query ------------------------------------------------------

# Verbs whose gerund the rules below would get wrong.
IRREGULAR_GERUNDS: dict[str, str] = {
    "be": "being",
    "begin": "beginning",
    "iron": "ironing",
    "lie": "lying",
    "tie": "tying",
    "unplug": "unplugging",
    "vacuum": "vacuuming",
}

_VOWEL_GROUPS = re.compile(r"[aeiouy]+")

# Leading words that are not verbs. An instruction starting with one of these is
# a description of a scene rather than an imperative — "There is a mixed pile of
# frozen fruits on the counter. Locate all the ..." — and running it through the
# gerund rules produces "thering". Those fall back to the canonical task name,
# which is always a verb phrase.
FUNCTION_WORDS = frozenset(
    {
        "a", "after", "all", "an", "and", "as", "at", "before", "both", "each",
        "first", "for", "from", "given", "if", "in", "it", "no", "on", "one",
        "or", "that", "the", "then", "there", "these", "this", "two", "using",
        "when", "while", "with", "you", "your",
    }
)

# Nouns that appear where a verb would. The canonical task *name* is usually a
# verb phrase — `Fold Cloth` — but not always: `Pj Sandwich Prep`, `Handover`,
# `Basketball`. Gerunding those gives "pjing", "handovering", "basketballing",
# so they get "doing" in front of them instead.
NOUN_HEADS = frozenset(
    {
        "bag", "basketball", "blocks", "bottle", "cable", "cloth", "cup",
        "dishwasher", "garment", "handover", "hockey", "laundry", "phone",
        "pj", "robo", "robot", "rope", "soccer", "table", "tv",
    }
)

NOT_A_VERB = FUNCTION_WORDS | NOUN_HEADS

# A query longer than this stops being a query and starts being a paragraph. The
# long-horizon rows carry multi-sentence instructions; those use the task name.
MAX_QUERY_WORDS = 16


@dataclass(frozen=True)
class Task:
    """One canonical task, ready to be used as a query."""

    rdt_id: str
    task_name: str
    instruction: str
    domain: str
    task_family: str
    granularity: str

    @property
    def difficulty(self) -> str:
        return DIFFICULTY_BY_GRANULARITY.get(self.granularity.lower(), "medium")

    @property
    def query(self) -> str:
        """The instruction as somebody would search for footage of it.

        The instruction is preferred, because it says what the hands do. It is
        dropped for the canonical task name when it is not a single imperative
        — a scene description, or three sentences of simulator set-up, is not
        something anybody typed into a search box — and whichever is used is
        then cut down to something query-shaped.
        """
        phrase = as_gerund_phrase(self.instruction) if usable_as_query(self.instruction) else ""
        return f"someone {shorten(phrase or as_gerund_phrase(self.task_name))}"

    @property
    def query_id(self) -> str:
        """A stable, readable id: the RDT number plus a slug of the name."""
        slug = re.sub(r"[^a-z0-9]+", "-", self.task_name.lower()).strip("-")
        return f"{self.rdt_id.lower()}-{slug[:40].rstrip('-')}"

    def as_dict(self) -> dict[str, object]:
        return {
            "id": self.query_id,
            "rdt_id": self.rdt_id,
            "task_name": self.task_name,
            "task_instruction": self.instruction,
            "query": self.query,
            "domain": self.domain,
            "task_family": self.task_family,
            "granularity": self.granularity,
            "difficulty": self.difficulty,
        }


@dataclass
class Selection:
    """A sampled eval set, with the accounting for how it was reached."""

    tasks: list[Task] = field(default_factory=list)
    total_rows: int = 0
    dropped: Counter[str] = field(default_factory=Counter)
    per_difficulty: Counter[str] = field(default_factory=Counter)
    per_family: Counter[str] = field(default_factory=Counter)
    shortfall: dict[str, int] = field(default_factory=dict)


def gerund(verb: str) -> str:
    """Turn a bare verb into its -ing form.

    English spelling rules, in the order that matters: an -e is dropped
    (``place`` → ``placing``) unless it is doubled or preceded by another vowel;
    a single final consonant after a single vowel group is doubled (``cut`` →
    ``cutting``, ``stir`` → ``stirring``) but only for a one-vowel-group word,
    which is what keeps ``clean`` from becoming ``cleanning`` and ``open`` from
    becoming ``openning``.
    """
    word = verb.lower()
    if word in IRREGULAR_GERUNDS:
        return IRREGULAR_GERUNDS[word]
    if word.endswith("ing"):
        return word
    if word.endswith("ie"):
        return word[:-2] + "ying"
    if word.endswith("e") and not word.endswith(("ee", "ae", "oe", "ye")):
        return word[:-1] + "ing"
    groups = _VOWEL_GROUPS.findall(word)
    if (
        len(groups) == 1
        and len(word) >= 3
        and word[-1] not in "aeiouywx"
        and word[-2] in "aeiou"
        and word[-3] not in "aeiou"
    ):
        return word + word[-1] + "ing"
    return word + "ing"


def as_gerund_phrase(instruction: str) -> str:
    """Rewrite an imperative instruction as the activity being performed.

    Some rows are normalised labels rather than sentences — `Adjust Bottle.` —
    and carry title case with them. Those are lowercased, because "someone
    adjusting Bottle" reads like a typo; a row that is already a sentence keeps
    its capitalisation, so a proper noun in it survives.
    """
    text = instruction.strip().rstrip(".").strip()
    if not text:
        return ""
    words = text.split()
    if len(words) > 1 and all(word[:1].isupper() for word in words):
        text = text.lower()
    head, _, tail = text.partition(" ")
    if head.lower() in NOT_A_VERB:
        # Not a verb, so there is no gerund to form. "doing" is clumsy and it is
        # never wrong, which is the right trade for a query.
        return re.sub(r"\s+", " ", f"doing {text}")
    phrase = f"{gerund(head)} {tail}".strip() if tail else gerund(head)
    return re.sub(r"\s+", " ", phrase)


def shorten(phrase: str) -> str:
    """Trim a phrase that is still too long to be a search query.

    A multi-step instruction searches worse than its first step: the words after
    the first `and` narrow the query to footage nobody titles that way. So the
    first clause is kept, and a first clause that is itself too long is cut at
    the word limit rather than carried.
    """
    words = phrase.split()
    if len(words) <= MAX_QUERY_WORDS:
        return phrase
    for joiner in (" and then ", " then ", " and "):
        head = phrase.split(joiner, 1)[0]
        if head != phrase and len(head.split()) <= MAX_QUERY_WORDS:
            return head
    return " ".join(words[:MAX_QUERY_WORDS])


def usable_as_query(instruction: str) -> bool:
    """Whether this instruction can be read as one imperative.

    Length is not part of this: a long imperative still says what the hands do,
    and `shorten` cuts it down. What disqualifies an instruction is being more
    than one sentence, or opening with something that is not a verb.
    """
    text = instruction.strip().rstrip(".").strip()
    words = text.split()
    if not words:
        return False
    if "." in text:  # more than one sentence
        return False
    return words[0].lower() not in FUNCTION_WORDS


def imperative_verbs(tasks: list[Task]) -> frozenset[str]:
    """The verbs the task map itself uses, read off its imperative instructions.

    Every usable instruction is an imperative, so its leading word is a verb.
    That makes the map its own lexicon — which is what lets the builder flag a
    query whose gerund came from a noun. The alternative, a hand-written verb
    list, would go stale the first time the map grew.
    """
    return frozenset(
        task.instruction.split()[0].lower().strip(".,")
        for task in tasks
        if usable_as_query(task.instruction)
    )


def suspect_gerunds(chosen: list[Task], verbs: frozenset[str]) -> dict[str, str]:
    """Sampled queries whose gerund was formed from a word that is not a verb.

    The canonical task name is usually a verb phrase — `Fold Cloth` — but some
    are noun phrases, and `Cheesy Pasta` gerunds into "cheesying". Those need a
    human to look, so they are named in the built set rather than corrected
    silently or left to be noticed in a scorecard.
    """
    flagged: dict[str, str] = {}
    for task in chosen:
        if usable_as_query(task.instruction):
            continue  # the instruction is an imperative; its head is a verb
        head = task.task_name.split()[0].lower().strip(".,")
        if head not in verbs and head not in NOT_A_VERB:
            flagged[task.rdt_id] = task.query
    return flagged


def canonical_family(family: str) -> str:
    """Collapse the family column's spellings onto one name."""
    name = (family or "").strip()
    return FAMILY_ALIASES.get(name, name or "Other")


def _unescape(text: str) -> str:
    """Undo the markdown escaping the spreadsheet export left behind."""
    return re.sub(r"\\([*\[\]<>_#!-])", r"\1", text).strip()


def load_task_map(path: Path | str = DEFAULT_TASK_MAP) -> list[Task]:
    """Read every row of the task map, unfiltered."""
    with Path(path).open(newline="", encoding="utf-8") as handle:
        return [
            Task(
                rdt_id=row["rdt_id"].strip(),
                task_name=_unescape(row["task_name"]),
                instruction=_unescape(row["instruction"]),
                domain=row["domain_l1"].strip(),
                task_family=canonical_family(row["task_family_l2"]),
                granularity=row["granularity"].strip(),
            )
            for row in csv.DictReader(handle)
        ]


def drop_reason(task: Task, raw_family: str | None = None) -> str | None:
    """Why this canonical task cannot be an eval query, or None if it can."""
    if task.domain in EXCLUDED_DOMAINS:
        return f"domain: {task.domain}"
    if (raw_family or task.task_family) in EXCLUDED_FAMILIES:
        return f"family: {raw_family or task.task_family}"
    if task.granularity in EXCLUDED_GRANULARITIES:
        return f"granularity: {task.granularity}"
    lowered = task.instruction.lower()
    if any(word in lowered for word in ROBOT_WORDING) or SIM_WORDING.search(lowered):
        return "instruction is written for a simulator or a rig"
    if UNUSABLE_INSTRUCTION.search(task.instruction):
        return "instruction has an unfilled slot, or is not English"
    if len(task.instruction.split()) < 2:
        return "instruction is a bare label"
    return None


def filmable(tasks: list[Task]) -> tuple[list[Task], Counter[str]]:
    """Split the map into what a person can be filmed doing, and why not."""
    kept: list[Task] = []
    dropped: Counter[str] = Counter()
    for task in tasks:
        reason = drop_reason(task)
        if reason:
            dropped[reason] += 1
        else:
            kept.append(task)
    return kept, dropped


def sample(
    tasks: list[Task],
    size: int,
    *,
    mix: dict[str, float] | None = None,
) -> Selection:
    """Choose `size` tasks, stratified by difficulty and spread over families.

    Difficulty follows the eval spec's 20/50/30 target. Within a tier the draw
    is round-robin over families in a fixed order, which maximises the number of
    families represented and lets the large families take the tail — a
    proportional draw would spend a fifth of the set on `Other`.
    """
    mix = mix or DIFFICULTY_MIX
    selection = Selection(total_rows=len(tasks))

    by_difficulty: dict[str, dict[str, list[Task]]] = defaultdict(lambda: defaultdict(list))
    for task in sorted(tasks, key=lambda t: t.rdt_id):
        by_difficulty[task.difficulty][task.task_family].append(task)

    quotas = _quotas(size, mix)
    for tier, quota in quotas.items():
        families = by_difficulty.get(tier) or {}
        # Smallest family first: a family with two rows must get its turn before
        # the round-robin runs out of quota on the big ones.
        order = sorted(families, key=lambda name: (len(families[name]), name))
        drawn: list[Task] = []
        cursors = dict.fromkeys(order, 0)
        while len(drawn) < quota and order:
            progressed = False
            for name in order:
                if len(drawn) >= quota:
                    break
                index = cursors[name]
                if index < len(families[name]):
                    drawn.append(families[name][index])
                    cursors[name] = index + 1
                    progressed = True
            if not progressed:
                break
        if len(drawn) < quota:
            selection.shortfall[tier] = quota - len(drawn)
        selection.tasks.extend(drawn)

    selection.tasks.sort(key=lambda t: t.rdt_id)
    selection.per_difficulty = Counter(task.difficulty for task in selection.tasks)
    selection.per_family = Counter(task.task_family for task in selection.tasks)
    return selection


def _quotas(size: int, mix: dict[str, float]) -> dict[str, int]:
    """Split `size` across the difficulty tiers, losing nothing to rounding."""
    quotas = {tier: int(size * share) for tier, share in mix.items()}
    remainder = size - sum(quotas.values())
    # Hand the rounding remainder to the largest tiers, largest share first.
    for tier in sorted(mix, key=lambda t: mix[t], reverse=True):
        if remainder <= 0:
            break
        quotas[tier] += 1
        remainder -= 1
    return quotas
