"""The frozen eval set itself.

`eval/queries.json` is cited by every scorecard, so it has to be two things at
once: reproducible from the task map, and well-formed as a set of queries. The
first is a diff; the second is the checks below. A failure here means either the
set is stale — rebuild it with `python eval/build_query_set.py` — or the
sampling rules changed in a way somebody needs to look at.
"""

from __future__ import annotations

import importlib.util
import json
import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]

_SPEC = importlib.util.spec_from_file_location(
    "eval_build_query_set", ROOT / "eval" / "build_query_set.py"
)
builder = importlib.util.module_from_spec(_SPEC)
sys.modules[_SPEC.name] = builder
_SPEC.loader.exec_module(builder)

# The set the builder currently produces. Each version gets its own file, so an
# old run record stays interpretable against the set it actually used.
CURRENT_PATH = ROOT / "eval" / f"queries-{builder.EVAL_VERSION}.json"
FROZEN = json.loads(CURRENT_PATH.read_text(encoding="utf-8"))
QUERIES = FROZEN["queries"]

# v1.0, kept for the runs that cite it.
V1_0_PATH = ROOT / "eval" / "queries.json"


def test_the_current_set_is_what_the_builder_builds() -> None:
    """A set that cannot be regenerated byte-for-byte is not frozen."""
    rebuilt = builder.serialise(builder.build(len(QUERIES)))
    assert rebuilt == CURRENT_PATH.read_text(encoding="utf-8"), (
        f"{CURRENT_PATH.name} is stale — run: python eval/build_query_set.py"
    )


def test_v1_0_is_left_alone_and_is_no_longer_rebuildable() -> None:
    """v1.0 is cited by published scorecards, so it must never be rewritten.

    It also cannot be rebuilt: the filter has since been tightened, which is the
    whole reason v1.1 exists. That is not a defect to fix by regenerating over
    it — a scorecard whose query set changed underneath it is unreadable. This
    test fails if somebody points the builder back at queries.json.
    """
    v1_0 = json.loads(V1_0_PATH.read_text(encoding="utf-8"))
    assert v1_0["eval_version"] == "v1.0"
    assert len(v1_0["queries"]) == 200
    assert builder.QUERIES_PATH != V1_0_PATH, (
        "the builder must not write over v1.0"
    )


def test_the_set_is_the_size_and_shape_the_eval_spec_asks_for() -> None:
    assert len(QUERIES) == 200
    difficulty = FROZEN["sampling"]["difficulty"]
    # The eval spec's difficulty axis: 20 / 50 / 30.
    assert difficulty == {"easy": 40, "hard": 60, "medium": 100}
    assert FROZEN["sampling"]["task_families"] >= 20
    assert not FROZEN["sampling"]["shortfall"]


def test_every_query_is_traceable_to_a_canonical_task() -> None:
    """The standard forbids invented task names; this is that rule, as a test."""
    task_map = (ROOT / "eval" / "task_map.csv").read_text(encoding="utf-8")
    for case in QUERIES:
        assert re.fullmatch(r"RDT-\d{5}", case["rdt_id"]), case
        assert f"\n{case['rdt_id']}," in task_map, f"{case['rdt_id']} is not in the task map"


def test_ids_are_unique() -> None:
    assert len({case["id"] for case in QUERIES}) == len(QUERIES)
    assert len({case["rdt_id"] for case in QUERIES}) == len(QUERIES)


def test_every_query_is_query_shaped() -> None:
    """Reported as a list, because one malformed query is a rule to fix."""
    malformed: list[str] = []
    for case in QUERIES:
        query = case["query"]
        words = query.split()
        if not query.startswith("someone "):
            malformed.append(f"{case['id']}: does not start with 'someone': {query}")
        # Either a gerund, or the "doing X" form used when the head is not a verb.
        elif not (words[1] == "doing" or words[1].endswith("ing")):
            malformed.append(f"{case['id']}: no gerund: {query}")
        # Long enough to say something, short enough to be a search.
        elif not 2 <= len(words) <= 18:
            malformed.append(f"{case['id']}: {len(words)} words: {query}")
        elif query != query.strip() or "  " in query:
            malformed.append(f"{case['id']}: whitespace: {query!r}")
    assert not malformed, malformed


def test_no_query_carries_simulator_wording() -> None:
    """A query naming a rig or a goal image is a benchmark, not footage."""
    banned = (
        "robot",
        "gripper",
        "end effector",
        "goal image",
        "goal zone",
        "target location",
        "target zone",
        "initial state",
        "[*",
        "{",
    )
    offenders = [
        f"{case['id']}: {case['query']}"
        for case in QUERIES
        if any(word in case["query"].lower() for word in banned)
        or re.search(r"\blevel\s?\d\b", case["query"].lower())
    ]
    assert not offenders, offenders


def test_every_query_carries_its_stratification() -> None:
    incomplete = [
        case["id"]
        for case in QUERIES
        if case["difficulty"] not in {"easy", "medium", "hard"}
        or not (case["task_family"] and case["granularity"] and case["task_instruction"])
    ]
    assert not incomplete, incomplete


def test_the_provenance_of_the_set_is_recorded() -> None:
    """A scorecard cites a version; the version has to say where it came from."""
    assert FROZEN["eval_version"]
    source = FROZEN["source"]
    for field in ("name", "owner", "sheet", "retrieved", "rows", "local_copy"):
        assert source.get(field), field
    pool = FROZEN["sampling"]["pool"]
    assert pool["rows_in_task_map"] > pool["filmable_by_a_person"] > len(QUERIES)
    assert pool["dropped"], "the rows that were dropped must be accounted for"


class TestTheFilterCatchesHardwareWithoutEatingRealFootage:
    """The 12 rows v1.0 shipped that nobody could ever film.

    They read like human actions with one extra word — `Pick Cube SO100` is the
    SO-100 arm picking a cube in a teleoperation episode — so the robot-wording
    list did not reach them. Every one returned zero candidates in a live run,
    putting a ~6% floor loss on v1.0's acceptance rate.

    The danger in fixing this with a word list is the opposite error, so the
    guards below matter more than the catches.
    """

    @staticmethod
    def _reason(name: str, instruction: str | None = None) -> str | None:
        from video_searching_agent.evaluation.task_map import Task, drop_reason

        return drop_reason(
            Task(
                rdt_id="RDT-99999",
                task_name=name,
                instruction=instruction if instruction is not None else f"{name}.",
                domain="Manipulation",
                task_family="Pick–Place & Transport",
                granularity="Benchmark Task",
            )
        )

    CAUGHT = [
        ("Pick Cube SO100", "task names robot hardware"),
        ("Pick Cube Widow Xai", "task names robot hardware"),
        ("Stack Green Cube On Yellow Cube Baked Tex In Scene", None),
        ("Blocks Ranking Rgb", None),
        ("Draw SVG", None),
        ("Lift Numbered Block", None),
    ]

    @pytest.mark.parametrize("name,expected", CAUGHT)
    def test_the_unfilmable_rows_are_dropped(self, name, expected):
        reason = self._reason(name)
        assert reason is not None, f"{name!r} should not survive the filter"
        if expected:
            assert reason == expected

    # Every one of these is a real thing in a real kitchen or workshop, and each
    # sits next to a banned word: texture/baked, mesh, cube, block, goal, panda.
    KEPT = [
        ("Check Dough Texture", "Check the texture of the dough."),
        ("Strain Pasta", "Pour the pasta through the mesh strainer."),
        ("Cut Butter", "Cut a block of butter into cubes."),
        ("Sweeten Coffee", "Drop a sugar cube into the coffee."),
        ("Score Goal", "Kick the soccer ball into the goal."),
        ("Bake Bread", "Take the baked loaf out of the oven."),
        ("Feed Panda", "Hand the bamboo to the panda."),
        ("Frame Photo", "Put the photograph in the frame."),
    ]

    @pytest.mark.parametrize("name,instruction", KEPT)
    def test_real_footage_is_not_eaten_by_the_word_list(self, name, instruction):
        assert self._reason(name, instruction) is None, (
            f"{instruction!r} is filmable and must survive"
        )

    def test_the_current_set_has_none_of_them_left(self):
        banned = re.compile(
            r"so100|widow ?xai|baked tex|in scene|\brgb\b|\bsvg\b|numbered block"
            r"|blocks ranking|cuboid|revolving.joint|visual goal|forbidden object",
            re.IGNORECASE,
        )
        offenders = [q["query"] for q in QUERIES if banned.search(q["query"])]
        assert not offenders, offenders

    def test_v1_0_still_contains_them_because_it_is_frozen(self):
        """The measurement that justified v1.1, pinned so the story stays true."""
        banned = re.compile(r"so100|widow ?xai|baked tex|\bsvg\b", re.IGNORECASE)
        v1_0 = json.loads(V1_0_PATH.read_text(encoding="utf-8"))["queries"]
        assert [q["rdt_id"] for q in v1_0 if banned.search(q["query"])]

    def test_v1_1_is_still_the_size_and_mix_the_spec_asks_for(self):
        """Dropping rows must not quietly shrink or unbalance the set."""
        assert len(QUERIES) == 200
        mix = FROZEN["sampling"]["difficulty"]
        assert mix == {"easy": 40, "hard": 60, "medium": 100}
        assert FROZEN["sampling"]["task_families"] == 25
